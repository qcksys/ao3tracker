CREATE FUNCTION "ao3track_local__record_change"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_ARGV[0] = 'auth' THEN
    IF NEW."updatedAt" IS NOT DISTINCT FROM OLD."updatedAt" AND NEW IS DISTINCT FROM OLD THEN
      NEW."updatedAt" := statement_timestamp();
    END IF;
  ELSIF NEW."rowUpdatedAt" IS NOT DISTINCT FROM OLD."rowUpdatedAt" AND NEW IS DISTINCT FROM OLD THEN
    IF TG_ARGV[0] <> 'work' OR
       (to_jsonb(NEW) - 'lastRefreshed' - 'refreshFailures') IS DISTINCT FROM
       (to_jsonb(OLD) - 'lastRefreshed' - 'refreshFailures') THEN
      NEW."rowUpdatedAt" := statement_timestamp();
    END IF;
  END IF;
  RETURN NEW;
END
